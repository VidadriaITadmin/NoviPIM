DECLARE
  @CustomerId bigint, @OrganizationId int, @NewTypeCode nvarchar(60),
  @CustomerKind nvarchar(20), @PackagingDiscountEnabled bit, @ValueDiscountEnabled bit,
  @B2bPlusEnabled bit, @B2bPlusValidFrom date, @B2bPlusValidTo date, @WebEnabled bit;

-- LEFT JOIN pim.CustomerWebProfile: brez obstojece vrstice gredo preostali stolpci na privzete
-- vrednosti stolpca (glej DEFAULT na pim.CustomerWebProfile), enako kot bi jih procedura sama
-- nastavila ob prvem vnosu s kartice stranke.
DECLARE candidate CURSOR LOCAL FAST_FORWARD FOR
  SELECT c.CustomerId, c.OrganizationId, m.CustomerTypeCode,
         p.CustomerKind, ISNULL(p.PackagingDiscountEnabled, 0), ISNULL(p.ValueDiscountEnabled, 0),
         ISNULL(p.B2bPlusEnabled, 0), p.B2bPlusValidFrom, p.B2bPlusValidTo, ISNULL(p.WebEnabled, 0)
  FROM b2b.Customer c
  JOIN @Mapping m ON m.OrganizationId = c.OrganizationId AND m.CustomerKey = c.CustomerKey
  LEFT JOIN pim.CustomerWebProfile p ON p.CustomerId = c.CustomerId
  WHERE p.CustomerTypeCode IS NULL OR p.CustomerTypeCode = N'';

OPEN candidate;
FETCH NEXT FROM candidate INTO @CustomerId, @OrganizationId, @NewTypeCode,
  @CustomerKind, @PackagingDiscountEnabled, @ValueDiscountEnabled,
  @B2bPlusEnabled, @B2bPlusValidFrom, @B2bPlusValidTo, @WebEnabled;

WHILE @@FETCH_STATUS = 0
BEGIN
  EXEC b2b.SaveCustomerWebProfile
    @OrganizationId = @OrganizationId, @CustomerId = @CustomerId, @CustomerTypeCode = @NewTypeCode,
    @CustomerKind = @CustomerKind, @PackagingDiscountEnabled = @PackagingDiscountEnabled,
    @ValueDiscountEnabled = @ValueDiscountEnabled, @B2bPlusEnabled = @B2bPlusEnabled,
    @B2bPlusValidFrom = @B2bPlusValidFrom, @B2bPlusValidTo = @B2bPlusValidTo,
    @WebEnabled = @WebEnabled, @ChangedBy = N'migracija-212';

  FETCH NEXT FROM candidate INTO @CustomerId, @OrganizationId, @NewTypeCode,
    @CustomerKind, @PackagingDiscountEnabled, @ValueDiscountEnabled,
    @B2bPlusEnabled, @B2bPlusValidFrom, @B2bPlusValidTo, @WebEnabled;
END

CLOSE candidate;
DEALLOCATE candidate;
